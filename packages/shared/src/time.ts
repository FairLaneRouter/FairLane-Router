export const HOUR_MS = 3_600_000

/**
 * Початок години за UTC. Сітка одна на всю систему — місцевого часу тут немає.
 *
 * Функція живе в `shared`, бо ту саму годину мають рахувати двоє: згортка,
 * яка пише рядок `group_hourly` (T028), і історія, яка його читає (T034). Дві
 * копії розійшлись би не одразу й не помітно, а зсувом графіка на годину —
 * тобто числом, яке виглядає правдоподібно й не є правдою.
 */
export function startOfHour(at: Date): Date {
  return new Date(Math.floor(at.getTime() / HOUR_MS) * HOUR_MS)
}
